-- ANFP - Esquema normalizado y poblamiento solicitado
-- Oracle Database 12c+ (IDENTITY). Ejecutar una vez en esquema vacio.

CREATE TABLE REGION (
  ID_REGION NUMBER(2) CONSTRAINT PK_REGION PRIMARY KEY,
  NOMBRE VARCHAR2(60) NOT NULL CONSTRAINT UN_REGION_NOMBRE UNIQUE
);

CREATE TABLE ASOCIACION (
  ID_ASOCIACION NUMBER(3) CONSTRAINT PK_ASOCIACION PRIMARY KEY,
  NOMBRE_ASOCIACION VARCHAR2(120) NOT NULL,
  FECHA_CREACION DATE NOT NULL,
  TIPO_ASOCIACION CHAR(1) NOT NULL,
  CONSTRAINT CK_ASOCIACION_FECHA CHECK (FECHA_CREACION >= DATE '1980-12-31'),
  CONSTRAINT CK_ASOCIACION_TIPO CHECK (TIPO_ASOCIACION IN ('P','A'))
);

CREATE TABLE NACIONALIDAD (
  ID_NACION NUMBER(3) GENERATED BY DEFAULT AS IDENTITY (START WITH 210 INCREMENT BY 2)
    CONSTRAINT PK_NACIONALIDAD PRIMARY KEY,
  DESCRIPCION VARCHAR2(40) NOT NULL CONSTRAINT UN_NACIONALIDAD_DESC UNIQUE
);

CREATE TABLE CLUB_FUTBOL (
  ID_CLUB NUMBER(4) CONSTRAINT PK_CLUB_FUTBOL PRIMARY KEY,
  NOMBRE_CLUB VARCHAR2(100) NOT NULL,
  PATRIMONIO NUMBER(15,0) DEFAULT 0 NOT NULL,
  UBICACION_CALLE VARCHAR2(160) NOT NULL,
  TIPO_CLUB VARCHAR2(15) NOT NULL,
  CONSTRAINT UN_CLUB_NOMBRE UNIQUE (NOMBRE_CLUB),
  CONSTRAINT CK_CLUB_PATRIMONIO CHECK (PATRIMONIO >= 0),
  CONSTRAINT CK_CLUB_TIPO CHECK (TIPO_CLUB IN ('Profesional','Amateur'))
);

CREATE SEQUENCE SQ_CLUB_FUTBOL START WITH 703 INCREMENT BY 4 NOCACHE NOCYCLE;

CREATE TABLE COMUNA (
  ID_COMUNA NUMBER(3) CONSTRAINT PK_COMUNA PRIMARY KEY,
  ID_REGION NUMBER(2) NOT NULL,
  NOMBRE VARCHAR2(80) NOT NULL,
  CONSTRAINT FK_COMUNA_REGION FOREIGN KEY (ID_REGION) REFERENCES REGION(ID_REGION),
  CONSTRAINT UN_COMUNA_REGION_NOMBRE UNIQUE (ID_REGION, NOMBRE)
);

CREATE TABLE ESCUELA_FUTBOL (
  ID_ESCUELA NUMBER(6) CONSTRAINT PK_ESCUELA_FUTBOL PRIMARY KEY,
  NOMBRE VARCHAR2(120) NOT NULL,
  CAPACIDAD NUMBER(6) NOT NULL,
  FECHA_FUNDACION DATE NOT NULL,
  CONSTRAINT CK_ESCUELA_CAPACIDAD CHECK (CAPACIDAD > 0)
);

CREATE TABLE TRABAJADOR (
  COD_INSCRIPCION NUMBER(10) CONSTRAINT PK_TRABAJADOR PRIMARY KEY,
  RUT NUMBER(8) NOT NULL,
  DV CHAR(1) NOT NULL,
  NOMBRES VARCHAR2(100) NOT NULL,
  APELLIDOS VARCHAR2(100) NOT NULL,
  SUELDO_BASE NUMBER(12,0) DEFAULT 0 NOT NULL,
  FECHA_NACIMIENTO DATE NOT NULL,
  GENERO CHAR(1) NOT NULL,
  ESTADO_CIVIL VARCHAR2(20) NOT NULL,
  TELEFONO_MOVIL VARCHAR2(20),
  EMAIL VARCHAR2(120),
  DIRECCION VARCHAR2(160) NOT NULL,
  ID_COMUNA NUMBER(3) NOT NULL,
  ID_NACION NUMBER(3) NOT NULL,
  CONSTRAINT UN_TRABAJADOR_RUT UNIQUE (RUT),
  CONSTRAINT CK_TRABAJADOR_DV CHECK (REGEXP_LIKE(DV, '^[0-9Kk]$')),
  CONSTRAINT CK_TRABAJADOR_GENERO CHECK (GENERO IN ('F','M','X')),
  CONSTRAINT CK_TRABAJADOR_SUELDO CHECK (SUELDO_BASE >= 0),
  CONSTRAINT FK_TRABAJADOR_COMUNA FOREIGN KEY (ID_COMUNA) REFERENCES COMUNA(ID_COMUNA),
  CONSTRAINT FK_TRABAJADOR_NACION FOREIGN KEY (ID_NACION) REFERENCES NACIONALIDAD(ID_NACION)
);

CREATE TABLE JUGADOR (
  COD_INSCRIPCION NUMBER(10) CONSTRAINT PK_JUGADOR PRIMARY KEY,
  PUESTO VARCHAR2(30) NOT NULL,
  PREMIOS_ACUMULADOS NUMBER(14,0) DEFAULT 0 NOT NULL,
  ID_ASOCIACION NUMBER(3) NOT NULL,
  ID_ESCUELA_ULTIMA NUMBER(6),
  ANIO_FIN_AMATEURISMO NUMBER(4),
  CONSTRAINT CK_JUGADOR_PREMIOS CHECK (PREMIOS_ACUMULADOS >= 0),
  CONSTRAINT CK_JUGADOR_ANIO CHECK (ANIO_FIN_AMATEURISMO BETWEEN 1900 AND 2100),
  CONSTRAINT FK_JUGADOR_TRABAJADOR FOREIGN KEY (COD_INSCRIPCION) REFERENCES TRABAJADOR(COD_INSCRIPCION),
  CONSTRAINT FK_JUGADOR_ASOCIACION FOREIGN KEY (ID_ASOCIACION) REFERENCES ASOCIACION(ID_ASOCIACION),
  CONSTRAINT FK_JUGADOR_ESCUELA FOREIGN KEY (ID_ESCUELA_ULTIMA) REFERENCES ESCUELA_FUTBOL(ID_ESCUELA)
);

CREATE TABLE PERSONAL_PLANTA (
  COD_INSCRIPCION NUMBER(10) CONSTRAINT PK_PERSONAL_PLANTA PRIMARY KEY,
  HORAS_TRABAJADAS NUMBER(6,2),
  VALOR_HORAS_EXTRAS NUMBER(12,0),
  CONSTRAINT CK_PERSONAL_HORAS CHECK (HORAS_TRABAJADAS IS NULL OR HORAS_TRABAJADAS >= 0),
  CONSTRAINT CK_PERSONAL_EXTRAS CHECK (VALOR_HORAS_EXTRAS IS NULL OR VALOR_HORAS_EXTRAS >= 0),
  CONSTRAINT FK_PERSONAL_TRABAJADOR FOREIGN KEY (COD_INSCRIPCION) REFERENCES TRABAJADOR(COD_INSCRIPCION)
);

CREATE TABLE PERMANENCIA_CLUB (
  COD_INSCRIPCION NUMBER(10) NOT NULL,
  ID_CLUB NUMBER(4) NOT NULL,
  FECHA_DESDE DATE NOT NULL,
  FECHA_HASTA DATE,
  CONSTRAINT PK_PERMANENCIA_CLUB PRIMARY KEY (COD_INSCRIPCION, ID_CLUB, FECHA_DESDE),
  CONSTRAINT CK_PERMANENCIA_FECHAS CHECK (FECHA_HASTA IS NULL OR FECHA_HASTA >= FECHA_DESDE),
  CONSTRAINT FK_PERMANENCIA_JUGADOR FOREIGN KEY (COD_INSCRIPCION) REFERENCES JUGADOR(COD_INSCRIPCION),
  CONSTRAINT FK_PERMANENCIA_CLUB FOREIGN KEY (ID_CLUB) REFERENCES CLUB_FUTBOL(ID_CLUB)
);

CREATE TABLE IDIOMA (
  ID_IDIOMA NUMBER(4) CONSTRAINT PK_IDIOMA PRIMARY KEY,
  NOMBRE VARCHAR2(50) NOT NULL CONSTRAINT UN_IDIOMA_NOMBRE UNIQUE
);

CREATE TABLE JUGADOR_IDIOMA (
  COD_INSCRIPCION NUMBER(10) NOT NULL,
  ID_IDIOMA NUMBER(4) NOT NULL,
  NIVEL_DOMINIO VARCHAR2(20) NOT NULL,
  CONSTRAINT PK_JUGADOR_IDIOMA PRIMARY KEY (COD_INSCRIPCION, ID_IDIOMA),
  CONSTRAINT CK_IDIOMA_NIVEL CHECK (NIVEL_DOMINIO IN ('Basico','Intermedio','Avanzado','Nativo')),
  CONSTRAINT FK_JUGADOR_IDIOMA_JUG FOREIGN KEY (COD_INSCRIPCION) REFERENCES JUGADOR(COD_INSCRIPCION),
  CONSTRAINT FK_JUGADOR_IDIOMA_IDI FOREIGN KEY (ID_IDIOMA) REFERENCES IDIOMA(ID_IDIOMA)
);

