-- Informe 1: asociaciones profesionales creadas despues de 2000.
SELECT ID_ASOCIACION AS ID, NOMBRE_ASOCIACION AS ASOCIACION,
       FECHA_CREACION AS CREADA, TIPO_ASOCIACION AS TIPO
FROM ASOCIACION
WHERE TIPO_ASOCIACION = 'P'
  AND FECHA_CREACION >= DATE '2001-01-01'
ORDER BY FECHA_CREACION DESC;

-- Informe 2: patrimonio en CLP y conversion a USD a $955 por dolar.
SELECT ID_CLUB AS CLUB, NOMBRE_CLUB,
       PATRIMONIO AS PATRIMONIO_EN_PESOS,
       ROUND(PATRIMONIO / 955, 2) AS PATRIMONIO_EN_DOLARES
FROM CLUB_FUTBOL
WHERE LOWER(NOMBRE_CLUB) LIKE '%a%'
  AND PATRIMONIO > 200000000
  AND TIPO_CLUB = 'Profesional'
ORDER BY ID_CLUB DESC;

